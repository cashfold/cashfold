// Bundles apps/web/src/adapters/sqlite-opfs/migrations/NNNN_name.sql into a TypeScript module, so the SQL
// ships with every bundler without special loaders. CI runs this and fails on a diff.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'apps/web/src/adapters/sqlite-opfs/migrations';
const files = readdirSync(dir).filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f)).sort();
if (files.length === 0) throw new Error('no migrations found');

const entries = files.map((file, i) => {
  const version = Number(file.slice(0, 4));
  if (version !== i + 1) throw new Error(`migration numbering must be gapless from 0001; got ${file} at position ${i + 1}`);
  return { version, name: file.slice(5, -4), sql: readFileSync(join(dir, file), 'utf8') };
});

const out = `// Generated by scripts/gen-migrations.mjs from the .sql files in this folder. Do not edit by hand.

export interface Migration {
  readonly version: number;
  readonly name: string;
  readonly sql: string;
}

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(dir, 'generated.ts'), out);
console.log(`generated.ts written (${entries.length} migrations)`);

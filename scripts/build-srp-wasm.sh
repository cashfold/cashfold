#!/usr/bin/env bash
# Rebuilds the SRP big-integer WASM module from packages/crypto/wasm/srp-bigint and installs it, with its SHA-256, next to
# the TypeScript adapter. The crate is pinned (Cargo.lock, crypto-bigint =0.7.5) and built with --locked, so the output is
# reproducible for a given Rust toolchain on Linux x86_64; CI rebuilds and compares.
#
# The compiler's output differs between host architectures (an arm64 Mac builds different bytes from an x86_64 Linux machine from the
# same source and toolchain), so Linux x86_64 is the reference. On any other machine this script runs itself in an x86_64 Linux
# container (Docker needed) and writes the result into the working tree.
set -euo pipefail
cd "$(dirname "$0")/.."
if [ "$(uname -s)-$(uname -m)" != "Linux-x86_64" ]; then
  exec docker run --rm --platform linux/amd64 -v "$PWD":/work -w /work ubuntu:24.04 bash scripts/build-srp-wasm.sh
fi
export PATH="$HOME/.cargo/bin:$PATH"
if ! command -v cargo >/dev/null 2>&1; then # a bare container: install rustup, which then reads the crate's rust-toolchain.toml
  apt-get update -qq && apt-get install -y -qq curl ca-certificates gcc >/dev/null
  curl -sSf https://sh.rustup.rs | sh -s -- -y --default-toolchain none >/dev/null 2>&1
fi
crate=packages/crypto/wasm/srp-bigint
out=packages/crypto/src/adapters/srp-wasm
(cd "$crate" && RUSTFLAGS="--remap-path-prefix=$HOME=~ --remap-path-prefix=$PWD=." cargo build --release --target wasm32-unknown-unknown --locked)
cp "$crate/target/wasm32-unknown-unknown/release/cashfold_srp_bigint.wasm" "$out/srp-bigint.wasm"
sha256sum "$out/srp-bigint.wasm" | cut -d' ' -f1 > "$out/srp-bigint.wasm.sha256"
printf "// Generated by scripts/build-srp-wasm.sh. The SHA-256 the adapter requires of the module's bytes.\nexport const SRP_BIGINT_SHA256 = '%s';\n" "$(cat "$out/srp-bigint.wasm.sha256")" > "$out/pinned.ts"
echo "srp-bigint.wasm $(wc -c < "$out/srp-bigint.wasm") bytes, sha256 $(cat "$out/srp-bigint.wasm.sha256")"

// Generates docs/protocol.md from the normative contracts (op-envelope.cddl, sync-api.openapi.yaml).
// The zod schemas in packages/protocol are held to the same contracts by openapi-contract.test.ts,
// so this document and the code cannot silently diverge. CI runs this and fails on a diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parse } from 'yaml';

const dir = 'specs/001-secure-finance-core/contracts';
const cddl = readFileSync(resolve(dir, 'op-envelope.cddl'), 'utf8').trimEnd();
const api = parse(readFileSync(resolve(dir, 'sync-api.openapi.yaml'), 'utf8'));

const rows = [];
for (const [path, item] of Object.entries(api.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    const secured = op.security && op.security.length === 0 ? 'no' : 'session';
    rows.push(`| \`${method.toUpperCase()}\` | \`${path}\` | ${secured} | ${op.summary ?? ''} |`);
  }
}

const out = `<!-- Generated by scripts/gen-protocol-docs.mjs. Do not edit by hand. -->

# Cashfold wire protocol

${api.info.description.trim().replace(/\n\s+/g, ' ')}

Version ${api.info.version}. Sources: \`${dir}/op-envelope.cddl\` and \`${dir}/sync-api.openapi.yaml\`.

## Endpoints

| Method | Path | Auth | Summary |
|---|---|---|---|
${rows.join('\n')}

## Wire formats (CDDL)

\`\`\`cddl
${cddl}
\`\`\`
`;
writeFileSync('docs/protocol.md', out);
console.log(`docs/protocol.md written (${rows.length} endpoints)`);

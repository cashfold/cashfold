// Writes THIRD_PARTY_NOTICES.md from the production dependency tree (T195). CI regenerates it and fails on any difference, so it
// cannot go stale. Pass --check to compare instead of writing.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const target = new URL('../THIRD_PARTY_NOTICES.md', import.meta.url);
const byLicense = JSON.parse(execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));

// Optional, platform-specific builds differ between machines (and are build tools, not part of what is shipped), so they are not listed:
// the image optimiser (unused: images are exported unoptimised), the CSS compilers' native binaries (lightningcss, Tailwind's oxide) and Next's compiler binaries.
const PLATFORM_ONLY = /^(@img\/sharp-|lightningcss-(darwin|linux|win32|freebsd|android)|@next\/swc-|@esbuild\/|@rollup\/rollup-|@oxc-|@tailwindcss\/oxide-)/;
const rows = [];
for (const [license, packages] of Object.entries(byLicense)) {
  for (const p of packages.filter((x) => !PLATFORM_ONLY.test(x.name))) for (const version of p.versions) rows.push({ name: p.name, version, license, homepage: p.homepage ?? '' });
}
rows.sort((a, b) => (a.name === b.name ? (a.version < b.version ? -1 : 1) : a.name < b.name ? -1 : 1));

const BUNDLED = [
  ['SQLite3 Multiple Ciphers (WebAssembly build, `@aztec/sqlite3mc-wasm`)', 'MIT / public domain', 'The database and its page cipher; verified against a pinned digest by `scripts/verify-sqlite3mc.mjs`.'],
  ['hash-wasm (Argon2id module)', 'MIT', 'Password stretching; checked against an independent implementation.'],
  ['SRP-6a big-integer module (`packages/crypto/src/adapters/srp-wasm`)', 'Cashfold, built from Rust sources and the crates listed in its `Cargo.lock`', 'Rebuilt in CI and compared with the committed bytes.'],
  ['Ubuntu font (`@fontsource/ubuntu`, woff2 files copied unmodified to `apps/web/public/fonts/`)', 'Ubuntu Font Licence 1.0', 'Licence text shipped as `fonts/UFL.txt`; not covered by the repository\'s AGPL grant.'],
  ['Electron (the desktop app\'s application shell, `apps/desktop`)', 'MIT', 'Ships in every desktop installer with its own `LICENSE.electron.txt`; a development dependency of the repository, so it is not in the production list below.'],
  ['Chromium (inside Electron)', 'BSD-3-Clause and the licences of its many components', 'The full texts ship in every desktop installer as `LICENSES.chromium.html`.'],
  ['Catalyst-derived UI components (`apps/web/src/ui/kit/`)', 'Tailwind Plus License', 'Isolated in one directory with its own licence notice (`LICENSE-TAILWIND-PLUS.md`); not covered by the repository\'s AGPL grant.'],
];

const out = [
  '# Third-party notices',
  '',
  'Cashfold includes the following third-party software. Each is used under its own licence, named below; the full text of each licence is in the package itself. This file is generated by `scripts/gen-third-party-notices.mjs` from the production dependency tree and checked in CI.',
  '',
  '## Components bundled as binaries',
  '',
  '| Component | Licence | Notes |',
  '| --- | --- | --- |',
  ...BUNDLED.map(([n, l, note]) => `| ${n} | ${l} | ${note} |`),
  '',
  `## Production dependencies (${rows.length})`,
  '',
  '| Package | Version | Licence | Home |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.homepage} |`),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const have = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (have !== out) {
    console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/gen-third-party-notices.mjs');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date');
} else {
  writeFileSync(target, out);
  console.log(`THIRD_PARTY_NOTICES.md written (${rows.length} packages)`);
}

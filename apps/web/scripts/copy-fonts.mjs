// Copies the Ubuntu font into public/fonts/ byte for byte and writes src/app/fonts.css (R-UX-07). Only weights 400, 500 and 700 and the
// subsets latin, latin-ext, cyrillic, cyrillic-ext and greek are shipped; each @font-face carries the `unicode-range` of its subset, so a
// browser downloads only the files the page's text needs. The files are served unmodified together with the Ubuntu Font Licence (UFL.txt).
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = dirname(createRequire(join(root, 'package.json')).resolve('@fontsource/ubuntu/package.json'));
const WEIGHTS = [400, 500, 700];
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek'];
const outDir = join(root, 'public/fonts');
mkdirSync(outDir, { recursive: true });

const faces = [];
for (const weight of WEIGHTS) {
  const css = readFileSync(join(pkg, `${weight}.css`), 'utf8');
  for (const subset of SUBSETS) {
    const name = `ubuntu-${subset}-${weight}-normal`;
    const file = join(pkg, 'files', `${name}.woff2`);
    if (!existsSync(file)) throw new Error(`${name}.woff2 is missing from @fontsource/ubuntu`);
    const range = new RegExp(`/\\* ${name} \\*/[^}]*?unicode-range:\\s*([^;]+);`).exec(css)?.[1];
    if (!range) throw new Error(`no unicode-range for ${name}`);
    copyFileSync(file, join(outDir, `${name}.woff2`));
    faces.push(`@font-face {
  font-family: 'Ubuntu';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url('/fonts/${name}.woff2') format('woff2');
  unicode-range: ${range};
}`);
  }
}
copyFileSync(join(pkg, 'LICENSE'), join(outDir, 'UFL.txt'));
writeFileSync(join(root, 'src/app/fonts.css'), `/* Generated by scripts/copy-fonts.mjs. Do not edit. */\n${faces.join('\n\n')}\n`);
console.log(`fonts: ${faces.length} files and UFL.txt copied to public/fonts/`);
